-- Vendedor 360° — schema inicial do Supabase
-- Execute no SQL Editor do projeto Supabase.
-- Não inclui dados reais de clientes nem chaves secretas.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  role text not null default 'rv' check (role in ('admin', 'gv', 'sv', 'rv')),
  assigned_code text,
  can_manage_catalog boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.clients (
  id uuid primary key default gen_random_uuid(),
  client_code text not null unique,
  gv_code text,
  sv_code text,
  rv_code text,
  activity text,
  cnpj text,
  legal_name text,
  trade_name text,
  address text,
  cep text,
  store_channel text,
  channel text,
  cluster text,
  eligible_ec boolean,
  store_platform text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists clients_gv_code_idx on public.clients(gv_code);
create index if not exists clients_sv_code_idx on public.clients(sv_code);
create index if not exists clients_rv_code_idx on public.clients(rv_code);
create index if not exists clients_cnpj_idx on public.clients(cnpj);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  product_code text not null unique,
  ean text,
  description text not null,
  price_7_days numeric(12,2),
  price_28_days numeric(12,2),
  dg_manual numeric(8,4),
  price_after_manual numeric(12,2),
  ec numeric(8,4),
  price_after_ec numeric(12,2),
  pg_plus numeric(8,4),
  df numeric(8,4),
  dg numeric(8,4),
  final_price numeric(12,2),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists products_ean_idx on public.products(ean);
create index if not exists products_description_idx on public.products using gin (to_tsvector('simple', description));

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  client_id uuid not null references public.clients(id),
  created_by uuid not null references public.profiles(id),
  status text not null default 'draft' check (status in ('draft', 'submitted', 'approved', 'cancelled')),
  notes text,
  subtotal numeric(14,2) not null default 0,
  discount_total numeric(14,2) not null default 0,
  total numeric(14,2) not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists orders_client_id_idx on public.orders(client_id);
create index if not exists orders_created_by_idx on public.orders(created_by);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id),
  product_code text not null,
  ean text,
  description text not null,
  quantity numeric(12,3) not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  discount numeric(12,2) not null default 0 check (discount >= 0),
  line_total numeric(14,2) generated always as (round(quantity * unit_price - discount, 2)) stored,
  created_at timestamptz not null default now()
);

create index if not exists order_items_order_id_idx on public.order_items(order_id);

-- Perfil criado automaticamente após cadastro no Supabase Auth.
-- O administrador deverá atribuir role e código corretos ao usuário.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    'rv'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- Funções auxiliares com execução controlada para as políticas RLS.
create or replace function public.my_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select p.role from public.profiles p where p.id = auth.uid()
$$;

create or replace function public.my_assigned_code()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select p.assigned_code from public.profiles p where p.id = auth.uid()
$$;

create or replace function public.my_can_manage_catalog()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((select p.role = 'admin' or p.can_manage_catalog from public.profiles p where p.id = auth.uid()), false)
$$;

create or replace function public.can_access_client(target_client_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((
    select
      p.role = 'admin'
      or (p.role = 'gv' and c.gv_code = p.assigned_code)
      or (p.role = 'sv' and c.sv_code = p.assigned_code)
      or (p.role = 'rv' and c.rv_code = p.assigned_code)
    from public.profiles p
    join public.clients c on c.id = target_client_id
    where p.id = auth.uid()
  ), false)
$$;

alter table public.profiles enable row level security;
alter table public.clients enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- Cada usuário lê seu perfil; administradores gerenciam todos os perfis.
drop policy if exists "profiles_read_self_or_admin" on public.profiles;
create policy "profiles_read_self_or_admin" on public.profiles
for select to authenticated
using (id = auth.uid() or public.my_role() = 'admin');

drop policy if exists "profiles_admin_manage" on public.profiles;
create policy "profiles_admin_manage" on public.profiles
for all to authenticated
using (public.my_role() = 'admin')
with check (public.my_role() = 'admin');

-- Clientes: carteira filtrada no próprio banco por GV, SV ou RV.
drop policy if exists "clients_read_assigned" on public.clients;
create policy "clients_read_assigned" on public.clients
for select to authenticated
using (public.can_access_client(id));

drop policy if exists "clients_admin_manage" on public.clients;
create policy "clients_admin_manage" on public.clients
for all to authenticated
using (public.my_role() = 'admin')
with check (public.my_role() = 'admin');

-- Produtos: leitura para usuários autenticados; escrita conforme permissão.
drop policy if exists "products_read_authenticated" on public.products;
create policy "products_read_authenticated" on public.products
for select to authenticated
using (true);

drop policy if exists "products_manage_permission" on public.products;
create policy "products_manage_permission" on public.products
for all to authenticated
using (public.my_can_manage_catalog())
with check (public.my_can_manage_catalog());

-- Pedidos: vendedor acessa pedidos dos clientes de sua carteira.
drop policy if exists "orders_read_accessible_client" on public.orders;
create policy "orders_read_accessible_client" on public.orders
for select to authenticated
using (public.can_access_client(client_id));

drop policy if exists "orders_insert_own_accessible_client" on public.orders;
create policy "orders_insert_own_accessible_client" on public.orders
for insert to authenticated
with check (created_by = auth.uid() and public.can_access_client(client_id));

drop policy if exists "orders_update_creator_or_admin" on public.orders;
create policy "orders_update_creator_or_admin" on public.orders
for update to authenticated
using (created_by = auth.uid() or public.my_role() = 'admin')
with check (created_by = auth.uid() or public.my_role() = 'admin');

-- Itens só podem ser consultados/incluídos/alterados dentro de pedidos acessíveis.
drop policy if exists "order_items_read_accessible" on public.order_items;
create policy "order_items_read_accessible" on public.order_items
for select to authenticated
using (exists (
  select 1 from public.orders o
  where o.id = order_id and public.can_access_client(o.client_id)
));

drop policy if exists "order_items_insert_own_order" on public.order_items;
create policy "order_items_insert_own_order" on public.order_items
for insert to authenticated
with check (exists (
  select 1 from public.orders o
  where o.id = order_id
    and (o.created_by = auth.uid() or public.my_role() = 'admin')
));

drop policy if exists "order_items_update_own_order" on public.order_items;
create policy "order_items_update_own_order" on public.order_items
for update to authenticated
using (exists (
  select 1 from public.orders o
  where o.id = order_id
    and (o.created_by = auth.uid() or public.my_role() = 'admin')
))
with check (exists (
  select 1 from public.orders o
  where o.id = order_id
    and (o.created_by = auth.uid() or public.my_role() = 'admin')
));

drop policy if exists "order_items_delete_own_order" on public.order_items;
create policy "order_items_delete_own_order" on public.order_items
for delete to authenticated
using (exists (
  select 1 from public.orders o
  where o.id = order_id
    and (o.created_by = auth.uid() or public.my_role() = 'admin')
));

-- Conceder acesso às tabelas e sequências para o papel autenticado.
grant usage on schema public to authenticated;
grant select, insert, update, delete on public.profiles, public.clients, public.products, public.orders, public.order_items to authenticated;
grant usage, select on all sequences in schema public to authenticated;
